class I18nManager {
  constructor() {
    this.currentLang = "en";
  }

  get lang() {
    return "en";
  }

  t(key) {
    const dict = translations.en;
    return dict[key] !== undefined ? dict[key] : key;
  }

  applyToDOM() {
    const html = document.documentElement;
    html.lang = "en";
    html.dir = "ltr";

    // Update all elements with data-i18n attribute
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const translation = this.t(key);
      if (translation) {
        if (el.tagName === "INPUT" && (el.type === "submit" || el.type === "button")) {
          el.value = translation;
        } else {
          el.textContent = translation;
        }
      }
    });

    // Update elements with placeholder translations
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      const translation = this.t(key);
      if (translation) {
        el.setAttribute("placeholder", translation);
      }
    });
  }

  /**
   * Helper to retrieve text from an object (prioritizing English fields)
   */
  getLocalized(obj, fieldName) {
    if (!obj) return "";
    
    // Check English field first: obj.title_en
    if (obj[`${fieldName}_en`]) {
      return obj[`${fieldName}_en`];
    }

    // Check direct property: obj.title
    if (obj[fieldName] && typeof obj[fieldName] === "string") {
      return obj[fieldName];
    }

    // Check object style: obj.title?.en
    if (obj[fieldName] && typeof obj[fieldName] === "object") {
      return obj[fieldName].en || obj[fieldName].ar || "";
    }

    // Fallback to Arabic field if English not set
    if (obj[`${fieldName}_ar`]) {
      return obj[`${fieldName}_ar`];
    }

    return "";
  }
}

export const i18n = new I18nManager();
